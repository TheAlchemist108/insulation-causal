"""Write RESULTS.md from outputs/ and paper/tables/ so the repository summary cannot drift from the paper."""
from pathlib import Path
import json
import numpy as np
import pandas as pd

R = Path(__file__).resolve().parents[1]
O, V, T = R / "outputs", R / "outputs" / "revision", R / "paper" / "tables"
pct = lambda v: -(np.exp(v) - 1) * 100
core = json.load(open(V / "core_info.json"))
autoc = json.load(open(V / "autoc.json"))
blp = pd.read_csv(V / "blp.csv"); blpt = pd.read_csv(V / "blp_with_type.csv")
gates, clan = pd.read_csv(V / "gates.csv"), pd.read_csv(V / "clan.csv")
subt = pd.read_csv(V / "subgroups_type.csv")
fi = pd.read_csv(O / "forest_importance.csv", index_col=0)["importance"]


def blp_md(df):
    out = ["| Model | Term | Coefficient (log points) | 95% CI | p |", "| --- | --- | --- | --- | --- |"]
    for r in df.itertuples():
        out.append(f"| {r.model} | {r.term} | {r.coef:.4f} | {r.lo:.4f} to {r.hi:.4f} | {r.p:.3f} |")
    return "\n".join(out)


